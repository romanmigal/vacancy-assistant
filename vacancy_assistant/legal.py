"""Организационно-правовые формы компаний — один список для всех мест, где из названия убирают «ООО», «LLC»:
короткое имя компании (sites), ключ для сравнения компаний (contacts), поиск компаний в резюме перед GigaChat (mask)
и фильтр по компании в окне (web/js/filters.js, companyTerm — тест сверяет его с этим списком)."""
import re

RU = ("ООО", "ПАО", "ОАО", "АО", "ЗАО", "НАО", "АНО", "ИП", "ГК", "ФГУП", "МУП", "Группа компаний")
EN = ("LLC", "Ltd", "Inc", "JSC")
FORMS = RU + EN

FORM = "(?:" + "|".join(re.escape(f).replace(r"\ ", " ") for f in FORMS) + r")\.?"   # «ООО», «Ltd.»
PREFIX = rf"^{FORM}\s+"                                   # в начале названия: «ООО Ромашка»
SUFFIX = r",?\s+(?:" + "|".join(EN) + r")\.?$"            # в конце: «Chamomile, LLC»
